#!/bin/bash
# ==============================================================================
# 脚本名称: harden-qemu-ga.sh
# 说明: 为 QEMU Guest Agent 施加 Systemd 内核级沙盒隔离
# 支持系统: Debian / Ubuntu / CentOS / RHEL / AlmaLinux / Rocky Linux
# ==============================================================================

set -e

# 终端颜色定义
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[0;33m'
BLUE='\033[0;34m'
NC='\033[0m'

# 1. 检查 root 权限
if [ "$EUID" -ne 0 ]; then
    echo -e "${RED}[错误] 请使用 root 权限或 sudo 运行此脚本！${NC}"
    exit 1
fi

# 2. 检查 qemu-guest-agent 是否安装
if ! systemctl list-unit-files | grep -q "^qemu-guest-agent\.service"; then
    echo -e "${RED}[错误] 系统中未检测到 qemu-guest-agent 服务，请先安装。${NC}"
    exit 1
fi

# 3. 设置基础屏蔽路径
# 路径前的 - 符号代表：即便该路径不存在也不抛出错误，保证服务正常启动
BASE_PATHS="-/etc/shadow -/etc/gshadow -/etc/ssh -/etc/sudoers -/var/lib/mysql"

# 处理用户自定义传入的路径
CUSTOM_PATHS=""
if [ $# -gt 0 ]; then
    for path in "$@"; do
        # 确保路径格式正确（自动补全 - 前缀）
        if [[ "$path" != -* ]]; then
            path="-$path"
        fi
        CUSTOM_PATHS="$CUSTOM_PATHS $path"
    done
else
    # 默认额外屏蔽参数（可根据需求修改此处的硬编码默认值）
    CUSTOM_PATHS="-/data -/admin -/secret"
fi

ALL_INACCESSIBLE="${BASE_PATHS}${CUSTOM_PATHS}"

echo -e "${BLUE}[+] 准备应用 QEMU Guest Agent Systemd 沙盒加固策略...${NC}"
echo -e "${YELLOW}[!] 完全屏蔽的路径清单:${NC} ${ALL_INACCESSIBLE}"

# 4. 创建 Drop-in 配置目录并写入 override.conf
OVERRIDE_DIR="/etc/systemd/system/qemu-guest-agent.service.d"
OVERRIDE_FILE="${OVERRIDE_DIR}/override.conf"

mkdir -p "$OVERRIDE_DIR"

cat <<EOF > "$OVERRIDE_FILE"
# Generated by harden-qemu-ga.sh
[Service]
# 1. 彻底隔离用户主目录 (/root, /home 对 Agent 显示为空)
ProtectHome=yes

# 2. 保护系统文件 (/usr, /boot, /etc 挂载为只读)
ProtectSystem=full

# 3. 彻底屏蔽敏感路径（沙盒内覆盖为 0 字节空节点）
InaccessiblePaths=${ALL_INACCESSIBLE}

# 4. 禁用提权与内核修改权限
NoNewPrivileges=yes
ProtectKernelTunables=yes
ProtectControlGroups=yes
EOF

echo -e "${GREEN}[✓] 配置文件已生成: ${OVERRIDE_FILE}${NC}"

# 5. 重载 Systemd 配置并重启服务
echo -e "${BLUE}[+] 重载 Systemd 并重启 qemu-guest-agent...${NC}"
systemctl daemon-reload
systemctl restart qemu-guest-agent

# 6. 验证配置生效状态
echo -e "${BLUE}[+] 正在验证已生效的沙盒规则:${NC}"
echo "----------------------------------------------------------------------"
systemctl show qemu-guest-agent -p ProtectHome -p ProtectSystem -p InaccessiblePaths -p NoNewPrivileges --no-pager
echo "----------------------------------------------------------------------"

echo -e "${GREEN}[✓] 加固完成！qemu-guest-agent 已被限制在沙盒中，服务商控制面板功能不受影响。${NC}"

